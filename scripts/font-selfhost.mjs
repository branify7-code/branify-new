// Self-host the 3 Google font families (Sora / Inter / JetBrains Mono) with
// the exact same static instances Google serves today (display=swap parity).
//
// Downloads the CSS2 stylesheet with a modern woff2 UA, parses the latin and
// latin-ext @font-face blocks, downloads each woff2 (SEQUENTIAL + retries —
// the sandbox network layer drops parallel bursts), and writes:
//   public/fonts/<family>-<subset>-<weight>.woff2
//   src/fonts.css  (unicode-range'd @font-face → bundled by Vite, no 3rd-party CSS)
//
// Weights kept = exactly what index.html loaded from Google (400-800 for
// Sora/Inter, 400/500 for JetBrains Mono). font-black(900)/font-light(300)
// keep resolving to the nearest loaded weight — identical to the old behavior.
import fs from 'node:fs';
import path from 'node:path';

const OUT_DIR = path.resolve(process.cwd(), 'public', 'fonts');
const CSS_OUT = path.resolve(process.cwd(), 'src', 'fonts.css');
fs.mkdirSync(OUT_DIR, { recursive: true });

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Sora:wght@400;500;600;700;800' +
  '&family=Inter:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;500&display=swap';

// Modern Chrome UA → woff2 + unicode-range responses
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

async function fetchRetry(url, opts = {}, tries = 4) {
  let lastErr;
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { ...opts, signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return res;
    } catch (e) {
      lastErr = e;
      await new Promise((r) => setTimeout(r, 800 * (i + 1)));
    }
  }
  throw lastErr;
}

function sleep(ms) { return new Promise((r) => setTimeout(r, ms)); }

const cssText = await (await fetchRetry(CSS_URL, { headers: { 'User-Agent': UA } })).text();

// Parse blocks: /* subset */ @font-face { ... font-family: 'X'; font-weight: N; src: url(...woff2) ... }
const blocks = [];
const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
let m;
while ((m = re.exec(cssText))) {
  const subset = m[1];
  const body = m[2];
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1];
  const url = /src:\s*url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
  const unicodeRange = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
  if (family && weight && url && unicodeRange) blocks.push({ subset, family, weight, url, unicodeRange });
}

const wanted = blocks.filter((b) => b.subset === 'latin' || b.subset === 'latin-ext');
console.log(`[fonts] css2 blocks: ${blocks.length}, keeping latin/latin-ext: ${wanted.length}`);
if (wanted.length < 24) console.log('[fonts] NOTE: expected 24 faces (12 weights x 2 subsets)');

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

const faces = [];
for (const b of wanted) {
  const file = `${slug(b.family)}-${b.subset}-${b.weight}.woff2`;
  const dest = path.join(OUT_DIR, file);
  const res = await fetchRetry(b.url, { headers: { 'User-Agent': UA } });
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(dest, buf);
  faces.push({ ...b, file, kb: (buf.length / 1024).toFixed(1) });
  console.log(`[fonts] ${file} ${kb(buf.length)} KB`);
  await sleep(120);
}
function kb(n) { return (n / 1024).toFixed(1); }

const totalKB = faces.reduce((a, f) => a + Number(f.kb), 0).toFixed(0);
console.log(`[fonts] downloaded ${faces.length} files, ${totalKB} KB total`);

// Emit fonts.css — bundled into the app CSS (same-origin, no render-blocking
// third-party request). font-display: swap matches the old &display=swap.
faces.sort((a, b) => a.family.localeCompare(b.family) || Number(a.weight) - Number(b.weight) || a.subset.localeCompare(b.subset));
const css = `/* Self-hosted fonts — generated by scripts/font-selfhost.mjs. Do not edit by hand.
   Subsets: latin + latin-ext (unicode-range kept identical to the Google CSS2 API,
   so the browser downloads exactly the same files it did before, minus the
   render-blocking third-party stylesheet). */
${faces
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${f.file}') format('woff2');
  unicode-range: ${f.unicodeRange};
}`
  )
  .join('\n\n')}
`;
fs.writeFileSync(CSS_OUT, css);
console.log('[fonts] wrote', CSS_OUT);
